# Uji tampilan HP: tombol Keluar (bilah atas & menu samping) dan tombol mata di kolom kata sandi (guru & siswa).
import time, sys
from playwright.sync_api import sync_playwright
exec(open('/home/claude/cbt/test/e2e_browser.py').read().split('# --- data ujian via API')[0])
OUT = sys.argv[1] if len(sys.argv) > 1 else '/tmp/hp'
with sync_playwright() as p:
    b = p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--no-sandbox', '--disable-features=LocalNetworkAccessChecks,PrivateNetworkAccessChecks'])
    ctx = b.new_context(viewport={'width': 375, 'height': 620}, is_mobile=True, has_touch=True, device_scale_factor=2)
    g = ctx.new_page(); g.route('**/*', rute); err = []; g.on('pageerror', lambda e: err.append(str(e)))
    g.goto(BASE + '/guru/'); g.wait_for_selector('input[type=password]')
    g.fill('input[autocomplete="username"]', 'admin'); g.fill('input[type=password]', 'admin123')
    g.click('.mata'); ok('guru: mata → kata sandi terlihat', g.get_attribute('.sandi-wrap input', 'type') == 'text')
    g.screenshot(path=OUT + '-guru-login.png')
    g.click('.mata'); ok('guru: mata lagi → tersembunyi', g.get_attribute('.sandi-wrap input', 'type') == 'password')
    g.click('button:has-text("Masuk")'); g.wait_for_selector('.page-head h1', timeout=10000); g.wait_for_timeout(500)
    ok('guru HP: tombol Keluar di bilah atas terlihat', g.is_visible('.topbar .topbar-keluar'))
    g.screenshot(path=OUT + '-guru-atas.png')
    g.click('.topbar button[aria-label="Menu"]'); g.wait_for_timeout(400)
    kot = g.evaluate("document.querySelector('.side-foot .btn-keluar').getBoundingClientRect().bottom")
    ok('guru HP: tombol Keluar di menu masih di dalam layar (tinggi 620)', kot <= 620, kot)
    g.screenshot(path=OUT + '-guru-menu.png')
    g.click('.side-tutup', position={'x': 340, 'y': 300}); g.wait_for_timeout(300)
    ok('guru HP: ketuk area gelap → menu tertutup', g.locator('.side.buka').count() == 0)
    g.click('.topbar .topbar-keluar'); g.wait_for_selector('text=Keluar dari aplikasi?', timeout=5000)
    ok('guru HP: Keluar meminta konfirmasi', True)
    g.click('.modal button:has-text("Keluar")'); g.wait_for_selector('input[type=password]', timeout=5000)
    ok('guru HP: keluar → kembali ke halaman masuk', True)
    g.goto(BASE + '/guru/'); g.fill('input[autocomplete="username"]', 'admin'); g.fill('input[type=password]', 'admin123'); g.click('button:has-text("Masuk")'); g.wait_for_selector('.page-head h1')
    g.goto(BASE + '/guru/#/akun'); g.wait_for_selector('text=Ganti kata sandi')
    ok('akun saya: 3 kolom kata sandi bermata', g.locator('.sandi-wrap .mata').count() == 3)
    s = ctx.new_page(); s.route('**/*', rute); serr = []; s.on('pageerror', lambda e: serr.append(str(e)))
    s.goto(BASE + '/ujian-cbt/'); s.wait_for_selector('input[type=password]')
    s.fill('input[autocomplete="username"]', '1001'); s.fill('input[type=password]', '1001')
    s.click('.mata'); ok('siswa: mata → kata sandi terlihat', s.get_attribute('.sandi-wrap input', 'type') == 'text')
    s.screenshot(path=OUT + '-siswa-login.png')
    s.click('button:has-text("Masuk")'); s.wait_for_selector('.btn-keluar', timeout=10000); s.wait_for_timeout(400)
    s.screenshot(path=OUT + '-siswa-daftar.png')
    s.click('.btn-keluar'); s.wait_for_selector('input[autocomplete="username"]', timeout=5000)
    ok('siswa: Keluar → halaman masuk, kata sandi kembali tersembunyi', s.get_attribute('.sandi-wrap input', 'type') == 'password')
    # mode aplikasi (CBT Ujian): kolom teks bertanda titik, mata membuka/menutup titiknya
    a = ctx.new_page(); a.route('**/*', rute)
    a.add_init_script("window.CBTAndroid = { apiUrl: () => '', info: () => '{}', kunci: () => {}, buka: () => {}, keluar: () => {} }")
    a.goto(BASE + '/ujian-cbt/'); a.wait_for_selector('.sandi-wrap input')
    kls1 = a.get_attribute('.sandi-wrap input', 'class') or ''
    a.click('.mata'); kls2 = a.get_attribute('.sandi-wrap input', 'class') or ''
    ok('mode aplikasi: titik disembunyikan/ditampilkan lewat mata', ('sandi' in kls1) and ('sandi' not in kls2), [kls1, kls2])
    ok('tanpa galat JavaScript', not err and not serr, err + serr)
    b.close()
print('LULUS' if not fails else 'GAGAL %d' % fails)
