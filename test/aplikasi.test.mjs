// Uji v2.7.0-CBT: token keluar aplikasi ujian & jadwal "wajib aplikasi".
import { createHash } from 'node:crypto';
const BASE = process.env.BASE || 'http://127.0.0.1:8787';
const call = async (a, d = {}, t = '') => (await fetch(BASE + '/api?a=' + a, { method: 'POST', body: JSON.stringify({ action: a, data: d, token: t }) })).json();
let fails = 0; const ok = (n, c, i) => { console.log((c ? '  ✓ ' : '  ✗ ') + n + (c ? '' : '  ' + String(JSON.stringify(i)).slice(0, 400))); if (!c) fails++; };
const sha = t => createHash('sha256').update(t).digest('hex');
const ADM = (await call('loginGuru', { username: 'admin', password: 'admin123' })).data.token;
const t0 = Date.now();
let r = await call('saveUjian', { nama: 'Ujian Aplikasi', bankId: 'bcontoh01', kelas: ['X-1'], mulai: t0 - 60000, selesai: t0 + 3600000, durasi: 30, pakaiToken: false, wajibApp: true }, ADM);
ok('jadwal wajib aplikasi tersimpan', r.ok && r.data.wajibApp === true, r);
const U = r.data;
ok('daftar jadwal tidak memuat token keluar', !('tokenKeluar' in U) && (await call('listUjian', {}, ADM)).data.every(u => !('tokenKeluar' in u)));
const S = (await call('loginSiswa', { nis: '1001', password: '1001' })).data.token;
r = await call('ujianSaya', {}, S);
ok('siswa: jadwal ditandai wajib aplikasi', r.data.find(u => u.id === U.id).wajibApp === true, r.data);
r = await call('mulaiUjian', { ujianId: U.id, perangkat: 'b1' }, S);
ok('dari browser biasa ditolak', !r.ok && r.code === 'WAJIB_APP', r);
r = await call('mulaiUjian', { ujianId: U.id, perangkat: 'a1', app: 'android' }, S);
ok('dari aplikasi diterima', r.ok, r);
const hash = r.data.keluarHash;
const mo = await call('monitorUjian', { ujianId: U.id }, ADM);
const tk = mo.data.ujian.tokenKeluar;
ok('monitor: token keluar 6 karakter', /^[A-Z2-9]{6}$/.test(tk), mo.data.ujian);
ok('paket siswa membawa sidik token keluar yang cocok (diperiksa tanpa internet)', hash === sha(U.id + ':' + tk), [hash]);
ok('token keluar tetap (sama setiap dibuka)', (await call('monitorUjian', { ujianId: U.id }, ADM)).data.ujian.tokenKeluar === tk);
ok('token keluar beda tiap jadwal', (await call('saveUjian', { ...U, id: '', nama: 'Lain' }, ADM)).ok);
const lain = (await call('listUjian', {}, ADM)).data.find(u => u.nama === 'Lain');
ok('…', (await call('monitorUjian', { ujianId: lain.id }, ADM)).data.ujian.tokenKeluar !== tk);
r = await call('cekTokenKeluar', { ujianId: U.id, token: 'SALAH1' }, S); ok('cek token keluar salah → false', r.ok && r.data === false, r);
r = await call('cekTokenKeluar', { ujianId: U.id, token: tk.toLowerCase() }, S); ok('cek token keluar benar → true', r.ok && r.data === true, r);
r = await call('cekTokenKeluar', { ujianId: U.id, token: tk }, ADM); ok('cek token keluar hanya untuk siswa', !r.ok, r);
await call('deleteUjian', { id: U.id, paksa: true, hapusHasil: true }, ADM); await call('deleteUjian', { id: lain.id, paksa: true, hapusHasil: true }, ADM);
console.log(fails ? `\n${fails} GAGAL` : '\nSEMUA LULUS');
process.exit(fails ? 1 : 0);
